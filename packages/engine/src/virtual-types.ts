// Integration-layer ambient modules. The framework-generic content layer stays unaware
// of Marko and virtual module APIs. Output is a script, not a module augmentation.
import type { ContentConfig } from "./content/index.ts";
import { writeFileIfChanged } from "./content/store.ts";

export async function generateVirtualTypes(config: ContentConfig, outPath: string): Promise<boolean> {
  const declarations = Object.keys(config.collections).flatMap((name) => {
    const data = `import("markopress/content").CollectionSchemas[${JSON.stringify(name)}]`;
    return [false, true].map((withContent) => [
      `declare module ${JSON.stringify(`virtual:mp/collection${withContent ? "-content" : ""}/${name}`)} {`,
      `  export const entries: Array<{`,
      `    id: string;`,
      `    slug: string;`,
      `    data: ${data};`,
      ...(withContent ? [
        `    segments: Array<{ type: "html"; html: string } | { type: "component"; component: Marko.Template<any, any> }>;`,
      ] : []),
      `    headings: Array<{ depth: number; slug: string; text: string }>;`,
      `  }>;`,
      `}`,
    ].join("\n"));
  });
  return writeFileIfChanged(outPath, [
    `/// <reference types="@marko/runtime-tags" />`,
    `// Generated by markopress — include .markopress/*.d.ts in tsconfig.`,
    ...declarations,
    "",
  ].join("\n"));
}
