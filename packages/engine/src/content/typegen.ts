/**
 * 类型生成：`.markopress/content.d.ts`。模板 + marker 替换（Astro types-generator 同法）。
 * schema 的类型推断不碰运行时值——从用户 config 模块的**类型**（typeof import）出发，
 * 生成文件只做「集合名 → data 形状」的映射，落到 index.ts 导出的 CollectionSchemas 上
 * （module augmentation 的合并点）。write-if-changed，避免 tsserver 抖动。
 */
import { writeFileIfChanged } from './store.ts'
import type { ContentConfig } from './types.ts'

const TEMPLATE = `// Generated by markopress (content layer) — do not edit.
// 改集合/schema 后由 dev server 或 build 重新生成；请加进 tsconfig include。
import type * as z from 'zod'

type MarkopressContentConfig = typeof import('@@CONFIG@@')

type InferEntrySchema<C extends keyof MarkopressContentConfig['collections']> = z.output<
	NonNullable<MarkopressContentConfig['collections'][C]['schema']>
>

declare module 'markopress/content' {
	interface CollectionSchemas {
		// @@COLLECTIONS@@
	}
}
`

export interface GenerateTypesOptions {
	/** 运行时内容配置（只取集合名与有无 schema） */
	config: ContentConfig
	/**
	 * 用户 config 模块的 import 说明符（相对生成文件的路径，形如 '../../content.config'）。
	 * 带不带扩展名跟随 app 的 tsconfig 模块解析策略。
	 */
	importSpecifier: string
	/** 生成文件路径，如 '<root>/.markopress/content.d.ts' */
	outPath: string
}

/** 生成类型文件；返回是否真的写入（内容未变 ⇒ false）。 */
export async function generateTypes(options: GenerateTypesOptions): Promise<boolean> {
	const lines = Object.entries(options.config.collections).map(([name, collection]) => {
		const type = collection.schema ? `InferEntrySchema<'${name}'>` : 'Record<string, unknown>'
		return `\t\t'${name}': ${type}`
	})
	const content = TEMPLATE.replace(
		"'@@CONFIG@@'",
		JSON.stringify(options.importSpecifier),
	).replace('// @@COLLECTIONS@@', lines.join('\n'))
	return writeFileIfChanged(options.outPath, content)
}
